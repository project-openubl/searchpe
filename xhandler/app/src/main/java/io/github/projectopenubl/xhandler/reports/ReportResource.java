package io.github.projectopenubl.xhandler.reports;

import io.github.projectopenubl.xhandler.api.ApiException;
import io.github.projectopenubl.xhandler.api.Ids;
import io.github.projectopenubl.xhandler.audit.Auditor;
import io.github.projectopenubl.xhandler.company.Company;
import io.github.projectopenubl.xhandler.company.CompanyResource;
import io.github.projectopenubl.xhandler.jobs.Job;
import io.github.projectopenubl.xhandler.jobs.Jobs;
import io.github.projectopenubl.xhandler.status.StatusResource;
import io.github.projectopenubl.xhandler.storage.FileStore;
import io.github.projectopenubl.xhandler.tenancy.Role;
import io.github.projectopenubl.xhandler.tenancy.TenantAccess;
import io.github.projectopenubl.xhandler.tenancy.TenantScope;
import jakarta.persistence.EntityManager;
import jakarta.transaction.Transactional;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import jakarta.ws.rs.GET;
import jakarta.ws.rs.POST;
import jakarta.ws.rs.Path;
import jakarta.ws.rs.PathParam;
import jakarta.ws.rs.core.Response;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.UUID;

/**
 * Registers of sales and purchases as files (DESIGN.md §11.9): CSV and Excel for people, PLE for
 * old periods, SIRE's layout. Generated by a job: {@code 202} with the job, then the report.
 */
@Path("/api/v1/tenants/{tenantId}/companies/{companyId}/reports")
public class ReportResource {

    public record ReportRequest(
            @NotBlank @Pattern(regexp = "sales|purchases") String register,
            @NotBlank @Pattern(regexp = "csv|xlsx|ple|sire") String format,
            @NotBlank @Pattern(regexp = "\\d{4}(0[1-9]|1[0-2])") String period) {}

    public record ReportView(
            UUID id, String register, String format, String period, String sunatEnv, String status, String fileName, Integer rows,
            String detail, UUID jobId, Instant createdAt, Instant doneAt) {}

    private final TenantAccess access;
    private final Jobs jobs;
    private final EntityManager em;
    private final FileStore files;
    private final Auditor auditor;

    public ReportResource(TenantAccess access, Jobs jobs, EntityManager em, FileStore files, Auditor auditor) {
        this.access = access;
        this.jobs = jobs;
        this.em = em;
        this.files = files;
        this.auditor = auditor;
    }

    @POST
    @Transactional
    public Response create(@PathParam("tenantId") UUID tenantId, @PathParam("companyId") UUID companyId, @Valid ReportRequest request) {
        TenantScope scope = access.enter(tenantId, Role.OPERATOR);
        Company company = CompanyResource.find(companyId);
        UUID id = Ids.newId();
        em.createNativeQuery("""
                        INSERT INTO xhandler.report (id, tenant_id, company_id, sunat_env, register, format, period, requested_by)
                        VALUES (:id, :t, :c, :env, :register, :format, :period, :by)""")
                .setParameter("id", id).setParameter("t", tenantId).setParameter("c", company.id).setParameter("env", company.sunatEnv)
                .setParameter("register", request.register()).setParameter("format", request.format()).setParameter("period", request.period())
                .setParameter("by", scope.actor().auditName()).executeUpdate();
        Job job = jobs.enqueue(scope, ReportJob.NAME, 4, Map.of("report_id", id.toString()), List.of(), null);
        em.createNativeQuery("UPDATE xhandler.report SET job_id = :job WHERE id = :id").setParameter("job", job.id).setParameter("id", id)
                .executeUpdate();
        auditor.record(scope, "report.requested", "company", companyId,
                Map.of("register", request.register(), "format", request.format(), "period", request.period()));
        return Response.status(202).entity(view(id)).build();
    }

    @GET
    @Transactional
    public List<ReportView> list(@PathParam("tenantId") UUID tenantId, @PathParam("companyId") UUID companyId) {
        access.enter(tenantId, Role.VIEWER);
        CompanyResource.find(companyId);
        @SuppressWarnings("unchecked")
        List<UUID> ids = em.createNativeQuery("SELECT id FROM xhandler.report WHERE company_id = :c ORDER BY created_at DESC LIMIT 100")
                .setParameter("c", companyId).getResultList();
        return ids.stream().map(this::view).toList();
    }

    @GET
    @Path("/{reportId}")
    @Transactional
    public ReportView get(@PathParam("tenantId") UUID tenantId, @PathParam("companyId") UUID companyId,
            @PathParam("reportId") UUID reportId) {
        access.enter(tenantId, Role.VIEWER);
        ReportView view = view(reportId);
        if (view == null || !companyId.equals(companyOf(reportId))) {
            throw ApiException.notFound();
        }
        return view;
    }

    @GET
    @Path("/{reportId}/file")
    @Transactional
    public Response file(@PathParam("tenantId") UUID tenantId, @PathParam("companyId") UUID companyId,
            @PathParam("reportId") UUID reportId) {
        TenantScope scope = access.enter(tenantId, Role.VIEWER);
        @SuppressWarnings("unchecked")
        List<Object[]> rows = em.createNativeQuery("SELECT file_ref, file_name, format FROM xhandler.report WHERE id = :id AND company_id = :c")
                .setParameter("id", reportId).setParameter("c", companyId).getResultList();
        if (rows.isEmpty() || rows.get(0)[0] == null) {
            throw ApiException.notFound();
        }
        auditor.record(scope, "report.downloaded", "company", companyId, Map.of("report_id", reportId.toString()));
        String name = (String) rows.get(0)[1];
        String type = switch ((String) rows.get(0)[2]) {
            case "csv" -> "text/csv; charset=utf-8";
            case "xlsx" -> "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";
            case "sire" -> "application/zip";
            default -> "text/plain; charset=utf-8";
        };
        return Response.ok(files.get((String) rows.get(0)[0])).type(type)
                .header("Content-Disposition", "attachment; filename=\"" + name + "\"").header("X-Content-Type-Options", "nosniff").build();
    }

    private UUID companyOf(UUID reportId) {
        List<?> found = em.createNativeQuery("SELECT company_id FROM xhandler.report WHERE id = :id").setParameter("id", reportId)
                .getResultList();
        return found.isEmpty() ? null : (UUID) found.get(0);
    }

    private ReportView view(UUID id) {
        @SuppressWarnings("unchecked")
        List<Object[]> rows = em.createNativeQuery("""
                        SELECT id, register, format, period, sunat_env, status, file_name, rows, detail, job_id, created_at, done_at
                        FROM xhandler.report WHERE id = :id""").setParameter("id", id).getResultList();
        if (rows.isEmpty()) {
            return null;
        }
        Object[] r = rows.get(0);
        return new ReportView((UUID) r[0], (String) r[1], (String) r[2], (String) r[3], (String) r[4], (String) r[5], (String) r[6],
                r[7] == null ? null : ((Number) r[7]).intValue(), (String) r[8], (UUID) r[9], StatusResource.toInstant(r[10]),
                StatusResource.toInstant(r[11]));
    }
}
