// The Searchpe resources users already have were written against the CRD of the Java operator
// (testdata/java-crd.yaml, generated by its last version): the CRD of this package must keep
// every field of it, with the same type.
func TestCRDKeepsTheFieldsOfTheJavaOperator(t *testing.T) {
	java := readCRD(t, "testdata/java-crd.yaml")
	golang := readCRD(t, "../../config/crd/bases/searchpe.openubl.io_searchpes.yaml")

	for _, name := range []struct{ what, java, golang string }{
		{"name", java.Name, golang.Name},
		{"group", java.Spec.Group, golang.Spec.Group},
		{"scope", string(java.Spec.Scope), string(golang.Spec.Scope)},
		{"kind", java.Spec.Names.Kind, golang.Spec.Names.Kind},
		{"plural", java.Spec.Names.Plural, golang.Spec.Names.Plural},
		{"singular", java.Spec.Names.Singular, golang.Spec.Names.Singular},
	} {
		if name.java != name.golang {
			t.Errorf("%s %q, want %q", name.what, name.golang, name.java)
		}
	}
	if len(golang.Spec.Versions) != 1 || golang.Spec.Versions[0].Name != java.Spec.Versions[0].Name {
		t.Fatalf("the CRD must serve only %s", java.Spec.Versions[0].Name)
	}
	if golang.Spec.Versions[0].Subresources == nil || golang.Spec.Versions[0].Subresources.Status == nil {
		t.Error("the CRD must have the status subresource")
	}

	compareSchemas(t, "", java.Spec.Versions[0].Schema.OpenAPIV3Schema, golang.Spec.Versions[0].Schema.OpenAPIV3Schema)
}

// compareSchemas checks that every property of java is in golang, with the same type.
func compareSchemas(t *testing.T, path string, java, golang *apiextensionsv1.JSONSchemaProps) {
	t.Helper()
	if golang == nil {
		t.Errorf("%s: missing", path)
		return
	}
	if java.Type != golang.Type {
		t.Errorf("%s: type %q, want %q", path, golang.Type, java.Type)
	}
	if java.Items != nil {
		var items *apiextensionsv1.JSONSchemaProps
		if golang.Items != nil {
			items = golang.Items.Schema
		}
		compareSchemas(t, path+"[]", java.Items.Schema, items)
	}
	for name, property := range java.Properties {
		var golangProperty *apiextensionsv1.JSONSchemaProps
		if p, ok := golang.Properties[name]; ok {
			golangProperty = &p
		}
		compareSchemas(t, path+"."+name, &property, golangProperty)
	}
}

func readCRD(t *testing.T, path string) *apiextensionsv1.CustomResourceDefinition {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	crd := &apiextensionsv1.CustomResourceDefinition{}
	if err := yaml.UnmarshalStrict(data, crd); err != nil {
		t.Fatalf("%s: %v", path, err)
	}
	return crd
}
